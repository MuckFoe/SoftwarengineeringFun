// Regenerates src/brand/icons-fallback.css from src/brand/iconMap.ts and lucide-static.
// Usage: node scripts/gen-fallback-icons.mjs   (run from frontend/)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const mapSrc = readFileSync(join(root, "src/brand/iconMap.ts"), "utf8");
const entries = [
  ...mapSrc.matchAll(/^\s*(\w+):\s*\{\s*audi:\s*"([^"]+)",\s*lucide:\s*"([^"]+)"\s*\}/gm),
];
if (entries.length === 0) throw new Error("no entries parsed from iconMap.ts");

const header = `/* GENERATED by scripts/gen-fallback-icons.mjs from src/brand/iconMap.ts. Do not edit.

   Fallback glyphs derived from Lucide (https://lucide.dev), stroke width 1.

   ISC License
   Copyright (c) for portions of Lucide are held by Cole Bemis 2013-2022 as part of Feather (MIT).
   All other copyright (c) for Lucide are held by Lucide Contributors 2022.
   Permission to use, copy, modify, and/or distribute this software for any purpose with or
   without fee is hereby granted, provided that the above copyright notice and this permission
   notice appear in all copies.

   brand.css (loaded later) overrides a name's mask-image with the supplied Audi set. */

.icon {
  display: inline-block;
  flex: none;
  background-color: currentColor;
  mask-size: contain;
  mask-repeat: no-repeat;
  mask-position: center;
  -webkit-mask-size: contain;
  -webkit-mask-repeat: no-repeat;
  -webkit-mask-position: center;
}
`;

const rules = entries.map(([, name, , lucide]) => {
  const raw = readFileSync(join(root, "node_modules/lucide-static/icons", `${lucide}.svg`), "utf8");
  const svg = raw
    .replace(/<!--[\s\S]*?-->\s*/g, "")
    .replace(/stroke-width="[^"]*"/, 'stroke-width="1"')
    .replace(/stroke="currentColor"/, 'stroke="black"')
    .replace(/\s+/g, " ")
    .replace(/> </g, "><")
    .trim();
  const uri = encodeURIComponent(svg).replace(/%20/g, " ").replace(/'/g, "%27");
  return `.icon[data-icon="${name}"] {\n  mask-image: url("data:image/svg+xml,${uri}");\n  -webkit-mask-image: url("data:image/svg+xml,${uri}");\n}\n`;
});

writeFileSync(join(root, "src/brand/icons-fallback.css"), `${header}\n${rules.join("\n")}`);
console.log(`wrote ${rules.length} icons`);
